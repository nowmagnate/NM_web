import type { TemplateTheme } from "../kit/schema";

/**
 * VERGE — Fern.

 * WHY THE GROUND MOVED. The catalog swatch was #F3F6F1, a very pale green that
 * sat within a couple of steps of Crisp's #F4F8F8 in the same category. Two
 * pale cool grounds at the same value read as the same paper.
 *
 * #EAF0E6 is a deeper, greener ground that actually carries the palette's
 * name, and it gives the planting photography something to sit against rather
 * than disappear into.
 *
 * DENSITY AIRY. A garden template that feels cramped is arguing against
 * itself.
 */
export const theme: TemplateTheme = {
  palette: {
    ink: "#1D2B21",
    bg: "#EAF0E6",
    accent: "#5E8C4E",
  },
  motion: "reveal",
  density: "airy",
  radius: 0,
};
